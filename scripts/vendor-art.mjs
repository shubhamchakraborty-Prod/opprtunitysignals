// Copies the illustrations and icons the web app uses into web/src/art.generated.js.
//   Illustrations: unDraw (undraw.co, unDraw licence) via the undraw-svg npm package.
//     The accent stays currentColor (set by CSS); dark tones are moved to the brand ink.
//   Icons: Material Symbols Rounded (Apache 2.0) via @material-symbols/svg-400;
//     '-fill' variants mark the active navigation item.
// Run after changing the lists below: node scripts/vendor-art.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ART = {
  jobs: 'factory', match: 'interview', trades: 'car-repair', compare: 'data-trends', plan: 'career-development',
  upcoming: 'construction-workers', regions: 'location-search', feeds: 'server-status', voice: 'no-data', evidence: 'file-searching',
  home: 'road-to-knowledge', learn: 'online-learning', path: 'graduation', market: 'growth-chart', institutes: 'teaching', signals: 'business-plan', invest: 'investment',
};
const ICONS = ['map', 'handshake', 'construction', 'compare_arrows', 'checklist', 'event_upcoming', 'travel_explore', 'cell_tower', 'forum', 'source_notes',
  'inbox', 'call', 'help', 'login', 'search', 'download', 'open_in_new', 'close', 'check_circle', 'warning', 'schedule', 'pause', 'play_arrow', 'menu',
  'location_on', 'arrow_drop_down', 'arrow_forward', 'info', 'verified', 'database', 'monitoring', 'factory', 'school', 'work', 'bolt', 'trending_up', 'hub', 'tune', 'lightbulb', 'school', 'apartment', 'trending_up', 'timeline', 'home', 'route', 'location_city', 'public', 'rocket_launch', 'currency_rupee', 'groups', 'north_east', 'engineering'];
const FILLED = ['map', 'handshake', 'construction', 'compare_arrows', 'checklist', 'event_upcoming', 'travel_explore', 'cell_tower', 'forum', 'source_notes', 'inbox', 'call', 'school', 'apartment', 'factory', 'hub', 'trending_up', 'timeline', 'home', 'route', 'location_city'];
const DARK = /#(3f3d56|2f2e41|090814|192534)/gi;

const art = {};
for (const [key, name] of Object.entries(ART)) {
  let svg = readFileSync(join(root, 'node_modules/undraw-svg/svgs', name + '.svg'), 'utf8');
  svg = svg.replace(/<title>.*?<\/title>/, '').replace(/\s(id|data-name)="[^"]*"/g, '').replace(DARK, '#1b1d3f').replace(/\s+/g, ' ').trim();
  art[key] = svg.replace('<svg ', '<svg aria-hidden="true" focusable="false" ');
}
const icon = (file) => readFileSync(join(root, 'node_modules/@material-symbols/svg-400/rounded', file), 'utf8')
  .replace(/\swidth="48" height="48"/, '').replace('<svg ', '<svg class="ico" aria-hidden="true" focusable="false" fill="currentColor" ').trim();
const icons = {};
for (const name of ICONS) icons[name] = icon(name + '.svg');
for (const name of FILLED) icons[name + '-fill'] = icon(name + '-fill.svg');

const out = `// Generated by scripts/vendor-art.mjs. Do not edit by hand.
// Illustrations: unDraw (https://undraw.co), unDraw licence. Icons: Material Symbols (https://fonts.google.com/icons), Apache 2.0.
/** @type {Record<string,string>} */
export const ART = ${JSON.stringify(art)};
/** @type {Record<string,string>} */
export const ICONS = ${JSON.stringify(icons)};
`;
writeFileSync(join(root, 'web/src/art.generated.js'), out);
console.log(`Wrote web/src/art.generated.js (${(out.length / 1024).toFixed(0)} KB, ${Object.keys(art).length} illustrations, ${Object.keys(icons).length} icons)`);
